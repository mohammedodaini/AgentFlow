"""Golden datasets: versioned questions with known-good answers.

Layer: evaluation. Files under `app/evaluation/data/`, not rows in a table.

**Why files.** A dataset change is a review event, exactly like a code change. In
a pull request a new question shows as a diff someone can argue with; in a
database it is an `INSERT` nobody sees, and six months later nobody can say
which questions the "94% recall" figure was measured against. Evals are the test
suite for model behaviour, and nobody keeps their tests in Postgres.

**Why they carry their own corpus.** An eval running against whatever documents
happened to be in the database would measure the database. Each dataset ships
the documents *and* the questions, so a run is reproducible on a laptop, in CI,
and six months from now.

The decision worth explaining
-----------------------------
Examples name **documents**, not chunks. The obvious design records the chunk id
that should be retrieved — and it is unusable here, because chunk ids do not
exist until ingestion and depend entirely on `chunk_size_tokens` and
`chunk_overlap_tokens`. Those two settings are precisely what M8 exists to tune.
A golden set keyed on chunk ids would have to be regenerated on every change to
the variable under test, which makes it a mirror rather than a measurement.

`answer_contains` does the same job for generation, for the same reason: text
that must appear in the answer survives re-chunking, re-ranking and a change of
model.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from functools import lru_cache
from pathlib import Path

DATA_ROOT = Path(__file__).parent / "data"
"""Datasets live inside the package, so they ship with it — the same argument as
`app/prompts/`. An eval that only runs where someone remembered to mount a
volume is an eval that does not run in CI."""


class DatasetError(Exception):
    """A dataset is missing or malformed.

    Its own type because the fix is always the same kind of thing — edit the
    JSON — and because a malformed dataset must never be silently skipped. An
    eval that quietly evaluates nothing reports perfect scores.
    """


@dataclass(frozen=True)
class GoldenDocument:
    """One document a dataset supplies as its corpus.

    `id` is the dataset's own stable label ("handbook"), not a database id. The
    database id is assigned at ingestion and differs on every run, so metrics
    are computed against these instead.
    """

    id: str
    title: str
    content: str


@dataclass(frozen=True)
class GoldenExample:
    """One question, and what a correct system does with it."""

    id: str
    question: str

    relevant_document_ids: set[str] = field(default_factory=set)
    """Which documents *should* be retrieved. Empty when the corpus genuinely
    cannot answer — see `expect_refusal`."""

    answer_contains: list[str] = field(default_factory=list)
    """Substrings a correct answer must include.

    Crude, deterministic, and free — which is what makes it the right first
    check. It cannot tell a good answer from a clumsy one; that is the judge's
    job. What it can do is catch an answer that is simply wrong, on every run,
    with no API key and no cost.
    """

    reference_answer: str = ""
    """What a good answer looks like, for the judge to compare against.

    Unused by the deterministic metrics. Written by a human who knows the
    domain, because a reference answer generated by the same model under
    evaluation measures agreement with itself.
    """

    expect_refusal: bool = False
    """This question *should* be refused.

    The most important examples in any RAG golden set, and the ones most often
    left out. A system that answers everything scores wonderfully on the
    questions its corpus covers and invents confident answers to the rest — and
    a dataset made only of answerable questions cannot tell the two apart.
    """


@dataclass(frozen=True)
class GoldenDataset:
    """A corpus and the questions asked of it."""

    name: str
    description: str
    documents: list[GoldenDocument]
    examples: list[GoldenExample]

    def document(self, document_id: str) -> GoldenDocument:
        """Look up a document by its dataset id."""
        for document in self.documents:
            if document.id == document_id:
                return document

        message = f"dataset {self.name!r} has no document {document_id!r}"
        raise DatasetError(message)


@lru_cache(maxsize=8)
def load_dataset(name: str) -> GoldenDataset:
    """Read and validate `data/<name>.json`.

    Validated on load rather than trusted, because every check below otherwise
    fails *silently* at run time: an example referencing a document that is not
    in the corpus scores 0 recall and looks like a retrieval regression;
    duplicate example ids overwrite each other in a report; an empty dataset
    produces a perfect score from zero measurements.

    That last one is the dangerous one. A green eval run over nothing is
    indistinguishable, in CI, from a green eval run over everything.
    """
    path = DATA_ROOT / f"{name}.json"

    if not path.is_file():
        available = sorted(candidate.stem for candidate in DATA_ROOT.glob("*.json"))
        message = f"No dataset named {name!r}. Available: {', '.join(available) or 'none'}"
        raise DatasetError(message)

    try:
        raw = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as error:
        message = f"dataset {name!r} is not valid JSON: {error}"
        raise DatasetError(message) from error

    dataset = GoldenDataset(
        name=raw.get("name", name),
        description=raw.get("description", ""),
        documents=[
            GoldenDocument(id=item["id"], title=item["title"], content=item["content"])
            for item in raw.get("documents", [])
        ],
        examples=[
            GoldenExample(
                id=item["id"],
                question=item["question"],
                relevant_document_ids=set(item.get("relevant_document_ids", [])),
                answer_contains=list(item.get("answer_contains", [])),
                reference_answer=item.get("reference_answer", ""),
                expect_refusal=bool(item.get("expect_refusal", False)),
            )
            for item in raw.get("examples", [])
        ],
    )

    _validate(dataset)
    return dataset


def _validate(dataset: GoldenDataset) -> None:
    """Refuse a dataset that would produce a meaningless score."""
    if not dataset.examples:
        message = f"dataset {dataset.name!r} has no examples — a run over nothing scores 1.0"
        raise DatasetError(message)

    if not dataset.documents:
        message = f"dataset {dataset.name!r} has no documents to search"
        raise DatasetError(message)

    ids = [example.id for example in dataset.examples]

    if len(set(ids)) != len(ids):
        duplicates = sorted({item for item in ids if ids.count(item) > 1})
        message = f"dataset {dataset.name!r} has duplicate example ids: {duplicates}"
        raise DatasetError(message)

    known = {document.id for document in dataset.documents}

    for example in dataset.examples:
        unknown = example.relevant_document_ids - known
        if unknown:
            message = (
                f"example {example.id!r} references documents not in the corpus: {sorted(unknown)}"
            )
            raise DatasetError(message)

        if example.expect_refusal and example.relevant_document_ids:
            # A contradiction the metrics cannot represent: the example claims
            # the corpus answers it *and* that it should not be answered.
            # Whichever the runner picked, the resulting number would be wrong.
            message = f"example {example.id!r} expects a refusal but names relevant documents"
            raise DatasetError(message)
